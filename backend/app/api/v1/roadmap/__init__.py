from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session
from typing import List
from datetime import datetime

from app.dependencies.auth import get_current_user
from app.dependencies.database import get_db
from app.models import User
from app.models.roadmap import Roadmap, RoadmapMilestone, LearningPlan, ProjectRecommendation
from app.schemas.roadmap_execution import RoadmapBase, RoadmapGenerateRequest

router = APIRouter(prefix="/roadmap", tags=["roadmap"])

@router.post("/generate/{career_id}", response_model=RoadmapBase)
def generate_roadmap(career_id: int, db: Session = Depends(get_db), current_user: User = Depends(get_current_user)):
    """Generates a personalized execution roadmap for a specific career."""
    # Mock adaptive generation logic
    roadmap = Roadmap(
        user_id=current_user.id,
        career_id=career_id,
        title="Personalized Execution Plan",
        description="Generated by AI based on your Career DNA and existing skills.",
        estimated_completion_months=12
    )
    db.add(roadmap)
    db.commit()
    db.refresh(roadmap)
    
    # Mock milestones
    m1 = RoadmapMilestone(
        roadmap_id=roadmap.id,
        title="Foundation Phase",
        description="Core concepts required for the career.",
        sequence_order=1,
        difficulty="Beginner"
    )
    m2 = RoadmapMilestone(
        roadmap_id=roadmap.id,
        title="Advanced Projects",
        description="Real-world application.",
        sequence_order=2,
        difficulty="Advanced"
    )
    db.add_all([m1, m2])
    db.commit()
    db.refresh(roadmap)
    
    return roadmap

@router.get("", response_model=List[RoadmapBase])
def get_user_roadmaps(db: Session = Depends(get_db), current_user: User = Depends(get_current_user)):
    return db.query(Roadmap).filter(Roadmap.user_id == current_user.id).all()

@router.get("/{roadmap_id}", response_model=RoadmapBase)
def get_roadmap(roadmap_id: int, db: Session = Depends(get_db), current_user: User = Depends(get_current_user)):
    roadmap = db.query(Roadmap).filter(
        Roadmap.id == roadmap_id, 
        Roadmap.user_id == current_user.id
    ).first()
    if not roadmap:
        raise HTTPException(status_code=404, detail="Roadmap not found")
    return roadmap

@router.put("/milestones/{milestone_id}/progress")
def complete_milestone(
    milestone_id: int, 
    status: str, 
    db: Session = Depends(get_db), 
    current_user: User = Depends(get_current_user)
):
    milestone = db.query(RoadmapMilestone).filter(RoadmapMilestone.id == milestone_id).first()
    if not milestone:
        raise HTTPException(status_code=404, detail="Milestone not found")
        
    milestone.status = status
    if status == "completed":
        milestone.completed_at = datetime.utcnow()
        
    db.commit()
    return {"status": "success", "milestone_status": milestone.status}
